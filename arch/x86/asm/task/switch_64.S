# Context switch for 64-bit x86 architecture.
#   void context_switch(struct task_context *saved,
#                       struct task_context *restored)

.global context_switch
.type context_switch, @function

context_switch:
    movq %rbx, (%rdi)
    movq %rsp, 8(%rdi)
    movq %rbp, 16(%rdi)
    movq %r12, 24(%rdi)
    movq %r13, 32(%rdi)
    movq %r14, 40(%rdi)
    movq %r15, 48(%rdi)

    movq (%rsi), %rbx
    movq 8(%rsi), %rsp
    movq 16(%rsi), %rbp
    movq 24(%rsi), %r12
    movq 32(%rsi), %r13
    movq 40(%rsi), %r14
    movq 48(%rsi), %r15

    ret