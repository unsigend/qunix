# Context switch for 32-bit x86 architecture.
#   void context_switch(struct task_context *saved,
#                       struct task_context *restored)

.global context_switch
.type context_switch, @function

context_switch:
    movl 4(%esp), %eax # saved
    movl 8(%esp), %edx # restored

    movl %ebx, (%eax)
    movl %esi, 4(%eax)
    movl %edi, 8(%eax)
    movl %ebp, 12(%eax)
    movl %esp, 16(%eax)

    movl (%edx), %ebx
    movl 4(%edx), %esi
    movl 8(%edx), %edi
    movl 12(%edx), %ebp
    movl 16(%edx), %esp

    ret